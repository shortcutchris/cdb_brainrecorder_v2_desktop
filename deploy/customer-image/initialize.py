#!/usr/bin/env python3
"""Fresh factory image only. Idempotent; never reset an existing customer profile."""
import hashlib
import json
import os
from pathlib import Path
import pwd
import shutil
import subprocess
import sys


def initialize(home, source, key, server, runtime, version):
    home, source, key = Path(home), Path(source), Path(key)
    data = home / '.local/share/cdb-recorder-local'
    app = home / '.local/share/cdb-recorder-app'
    agent = home / '.local/share/cdb-recorder-agent'
    # Refuse adoption of an existing installation. Resume only our own incomplete build.
    marker = home / '.cdb-factory-initializing'
    done = home / '.cdb-factory-ready'
    if done.exists(): return False
    if not marker.exists() and any(p.exists() for p in (data, app, agent)):
        raise ValueError('Existing installation: factory initialization refused.')
    marker.touch(mode=0o600)
    sys.path.insert(0, str(source))
    from fleet.common import save
    release = app / 'releases/factory'
    if not release.exists():
        shutil.copytree(source, release, ignore=shutil.ignore_patterns('__pycache__'))
    (data / 'models').mkdir(parents=True, exist_ok=True)
    if not (release / 'models').exists(): (release / 'models').symlink_to(data / 'models')
    if not (app / 'current').exists(): (app / 'current').symlink_to(release)
    if not agent.exists(): agent.mkdir(parents=True)
    shutil.copytree(source / 'fleet', agent / 'fleet', dirs_exist_ok=True)
    management = data / 'management'; management.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(key, management / 'release-public.pem')
    for path, value in [
        (app / 'accepted.json', {'version': version, 'sequence': 0, 'release': 'factory'}),
        (app / 'shared.json', {'models': str(data / 'models')}),
        (management / 'config.json', {'server': server, 'updates_root': str(app), 'runtime': runtime}),
        (data / 'first-start.json', {'required': True, 'step': 'welcome', 'completed': False})]:
        if not path.exists(): save(path, value)
    return True


def main():
    if not Path('/etc/cdb-factory-image.json').is_file(): raise SystemExit('Factory image required')
    guard = Path('/var/lib/cdb-factory')
    guard.mkdir(mode=0o700, parents=True, exist_ok=True)
    if (guard / 'ready').exists(): return
    # Root bootstrap must never re-enter a user-writable home on later boots.
    # An interrupted bootstrap requires image recovery, not blind privileged replay.
    with (guard / 'started').open('x') as stamp:
        stamp.write('factory bootstrap\n'); stamp.flush(); os.fsync(stamp.fileno())
    config = json.loads(Path('/etc/cdb-factory-image.json').read_text())
    user = pwd.getpwnam('cdb')
    freeze = subprocess.check_output(['/opt/cdb/runtime/bin/python', '-m', 'pip', 'freeze']).decode()
    version = subprocess.check_output(['/opt/cdb/runtime/bin/python', '-c', 'import sys;print(str(sys.version_info[:2]),end="")']).decode()
    runtime = hashlib.sha256((version + freeze).encode()).hexdigest()
    created = initialize(user.pw_dir, '/opt/cdb/source', '/opt/cdb/factory/release-public.pem', config['server'], runtime, config['version'])
    if created:
        # Only a new factory profile is owned here; no recursive migration of user content.
        for folder in ('.local/share/cdb-recorder-local', '.local/share/cdb-recorder-app', '.local/share/cdb-recorder-agent'):
            subprocess.run(['chown', '-R', 'cdb:cdb', str(Path(user.pw_dir) / folder)], check=True)
        serial = Path('/sys/firmware/devicetree/base/serial-number').read_bytes().rstrip(b'\0')
        name = 'brain-' + hashlib.sha256(serial).hexdigest()[:8]
        Path('/etc/hostname').write_text(name + '\n')
        hosts = Path('/etc/hosts')
        lines = [line for line in hosts.read_text().splitlines() if not line.startswith('127.0.1.1')]
        hosts.write_text('\n'.join(lines) + '\n127.0.1.1\t' + name + '\n')
        subprocess.run(['hostname', name], check=True)
        (Path(user.pw_dir) / '.cdb-factory-ready').touch(mode=0o600)
        (Path(user.pw_dir) / '.cdb-factory-initializing').unlink()
    with (guard / 'ready').open('x') as stamp:
        stamp.write('ready\n'); stamp.flush(); os.fsync(stamp.fileno())
    # No SSH daemon is enabled. OS identity is generated by systemd on first boot.

if __name__ == '__main__':
    os.umask(0o077)
    main()
